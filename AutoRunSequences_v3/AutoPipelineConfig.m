function cfg = AutoPipelineConfig()
% Central configuration for T1 semi-auto orchestration.
%
% Primary knobs for future experiments:
% 1) cfg.stepOrder         -> choose which sequence runs and in what order
% 2) cfg.steps.<StepId>    -> parameter sources/constants/derived values
% 3) cfg.steps.<StepId>.fitFunction -> post-run fit hook function name
% 4) cfg.plotting          -> per-sequence live plotting behavior in T1_SemiAuto_Run
% 5) cfg.outerAutomation   -> optional (T, B) schedule loop above the inner flow

cfg = struct();

% Edit this list to reorder/disable/insert steps.
cfg.stepOrder = {'Presets', 'ESR', 'Rabi', 'ESR2', 'Rabi2', 'T00', 'T11'};

