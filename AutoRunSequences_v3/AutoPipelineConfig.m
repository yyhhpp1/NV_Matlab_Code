% Live plotting behavior during T1_SemiAuto_Run:
% - maxCtrToPlot: skip plotting when counter-gate number is too large.
% - rules: {sequenceName, plotFunction, liveFitFunction}
%   liveFitFunction can be '' if no per-iteration fit is needed.
